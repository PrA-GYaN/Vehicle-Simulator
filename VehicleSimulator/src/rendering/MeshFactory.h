#pragma once
//===========================================================================
//  MeshFactory.h  --  procedural primitive generation.
//
//  Every mesh in the simulator is generated here. No model files, no asset
//  pipeline, no importer dependency. For a debug-oriented vehicle dynamics
//  tool that is the right trade: the shapes are simple, and being able to
//  drive them directly from the vehicle parameters means the visual always
//  matches the configuration.
//===========================================================================

#include <vector>

#include <glm/glm.hpp>

#include "config/VehicleParameters.h"
#include "environment/Track.h"
#include "rendering/Mesh.h"

namespace vsim {

struct MeshData {
    std::vector<Vertex>     vertices;
    std::vector<gl::GLuint> indices;

    void append(const MeshData& other);
    void uploadTo(Mesh& mesh, gl::GLenum primitive = gl::TRIANGLES) const;
};

namespace meshfactory {

//---------------------------------------------------------------------------
//  Low-level emitters.
//
//  Public because the two procedural MODEL builders - CarMesh.h and
//  TrackMesh.h - assemble their shapes out of these rather than out of whole
//  primitives. Everything above the line is a finished object; everything
//  here is a face.
//---------------------------------------------------------------------------

/// Quad a-b-c-d with an explicit normal. Wound so that a-b-c-d in that order
/// is counter-clockwise seen from the side the normal points at.
void addQuad(MeshData& m, const glm::vec3& a, const glm::vec3& b,
             const glm::vec3& c, const glm::vec3& d,
             const glm::vec3& normal, const glm::vec3& color);

/// Quad whose normal is derived from its own corners, and whose winding is
/// then corrected to agree with `outward`. Used wherever the geometry is
/// generated by a formula and getting the vertex order right by hand would be
/// guesswork - a lofted hull, a swept ribbon.
void addQuadOriented(MeshData& m, const glm::vec3& a, const glm::vec3& b,
                     const glm::vec3& c, const glm::vec3& d,
                     const glm::vec3& outward, const glm::vec3& color);

/// Triangle with a derived normal, wound to agree with `outward`.
void addTriangleOriented(MeshData& m, const glm::vec3& a, const glm::vec3& b,
                         const glm::vec3& c, const glm::vec3& outward,
                         const glm::vec3& color);

/// Arbitrary six-faced solid from eight corners: c[0..3] is one face (in
/// order around it), c[4..7] the matching face on the other side. Tapered,
/// sheared and twisted boxes all come from this - wings, splitters, kerbs,
/// spokes - so none of them needs its own generator.
void addHexahedron(MeshData& m, const glm::vec3 c[8], const glm::vec3& color);

/// Hexahedron with a different colour on its top face (c[4..7]). Kerbs and
/// painted kit use this so the visible surface reads differently from the
/// sides without a second mesh.
void addHexahedronTopped(MeshData& m, const glm::vec3 c[8],
                         const glm::vec3& side, const glm::vec3& top);

/// Axis-aligned box centred on the origin.
MeshData box(const glm::vec3& halfExtents, const glm::vec3& color);

/// Box with its own centre offset, so a body can be positioned relative to
/// the vehicle's rear-axle origin without a separate transform.
MeshData boxAt(const glm::vec3& centre, const glm::vec3& halfExtents,
               const glm::vec3& color);

/// Cylinder used for wheels. The axis runs along LOCAL +Z, which is the
/// vehicle's "right" direction - i.e. a wheel's spin axis. Radius is in the
/// X-Y plane so the wheel rolls in the vehicle's X-Y plane.
MeshData wheel(float radius, float width, int segments, const glm::vec3& color);

/// Flat ground quad in the X-Z plane at y = 0.
MeshData groundPlane(float halfExtent, const glm::vec3& color);

/// Grid of lines in the X-Z plane. Returns LINES-primitive data.
MeshData grid(float halfExtent, float spacing,
              const glm::vec3& minorColor, const glm::vec3& majorColor,
              int majorEvery = 10);

/// Road surface generated from a track centreline, as a triangle strip of
/// quads. Slightly raised off the ground plane to avoid z-fighting.
MeshData roadSurface(const Track& track, const glm::vec3& color);

/// Dashed centre line plus solid edge lines for a track.
MeshData roadMarkings(const Track& track, float dashLength, float gapLength,
                      float lineWidth, const glm::vec3& color);

/// A simple low-poly cone, used for slalom markers and direction indicators.
MeshData cone(float radius, float height, int segments, const glm::vec3& color);

/// Cylinder from `base` to `base + axis`, capped at both ends. The axis may
/// point anywhere - posts, exhaust pipes, tyre-wall stacks and light housings
/// all come from this one generator.
MeshData cylinderAlong(const glm::vec3& base, const glm::vec3& axis,
                       float radius, int segments, const glm::vec3& color,
                       bool capped = true);

/// Small sphere-ish icosphere for the centre-of-mass marker.
MeshData sphere(float radius, int subdivisions, const glm::vec3& color);

} // namespace meshfactory
} // namespace vsim
